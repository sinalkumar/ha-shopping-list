"""Build public store choices from a local grocer.nz base database.

Development/release tool only: pip install duckdb, then run with --database.
The HA integration does not depend on DuckDB or read the base database.
Only enabled store IDs, vendor names and public store names are exported.
"""

import argparse
from pathlib import Path


def main() -> None:
    import duckdb  # Development-only, never imported by the integration.

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", required=True)
    args = parser.parse_args()
    with duckdb.connect(args.database, read_only=True) as conn:
        rows = conn.execute(
            "SELECT s.id, s.name, s.vendor_id FROM public_stores s "
            "WHERE s.is_enabled AND s.vendor_id IN (1, 3) ORDER BY s.id"
        ).fetchall()
    target = (
        Path(__file__).resolve().parents[1]
        / "custom_components/smart_shopping_route/stores.py"
    )
    content = '"""Public grocer.nz store choices; generated by scripts/update_store_catalog.py.\n\nRefresh at release time from the public base database. No household data.\n"""\n\nHISTORY_STORES: dict[int, tuple[str, str]] = {\n'
    for store_id, name, vendor_id in rows:
        content += f"    {store_id}: {('woolworths' if vendor_id == 1 else 'paknsave', name)!r},\n"
    target.write_text(content + "}\n", encoding="utf-8")
    print(f"Exported {len(rows)} public stores to {target}")


if __name__ == "__main__":
    main()
